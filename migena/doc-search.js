/*
 * FILE: migena/doc-search.js
 *
 * Purpose: the "query tower" of the documentation search that appears
 * on the seven official Migena document pages. It encodes what the
 * reader types into the same hashed vector space as the pre-built
 * section vectors in migena/search-index.js, scores every section by
 * cosine similarity, then renders a ranked results panel under the
 * box. It understands meaning (via the concept lexicon shipped inside
 * the index), tolerates typos (character trigrams) and updates as the
 * reader types.
 *
 * Deliberately NOT for: analytics. The client portal carries no
 * Google Analytics tag, so unlike assets/service-search.js this file
 * never reports search terms anywhere; everything stays in the
 * browser.
 *
 * Invariants relied upon:
 *   1. normalise, stem, tokenise, fnv1a and featurise MUST match
 *      scripts/build_search_index.py step for step. The concept
 *      lexicon, stopwords, weights and dimension are read from the
 *      index itself, so only the maths is mirrored here, exactly as
 *      assets/service-search.js mirrors it for the home page.
 *   2. The element ids below (doc-search-input, doc-search-status,
 *      doc-search-results) must match the markup every page ships.
 *
 * Works in the standalone offline copy too: that page inlines this
 * file and migena/search-index.js, so nothing here may assume a
 * particular path or origin.
 */
(function initDocSearch() {
    'use strict';

    // Step 1: the two halves of the pair. The index is generated by
    // scripts/build_search_index.py; the elements come from the page.
    var idx = window.MIGENA_SEARCH_INDEX;
    var input = document.getElementById('doc-search-input');
    var status = document.getElementById('doc-search-status');
    var results = document.getElementById('doc-search-results');
    if (!idx || !input || !status || !results) {
        return;
    }

    var DIM = idx.dim;
    var W_WORD = idx.weights[0];
    var W_CONCEPT = idx.weights[1];
    var W_TRIGRAM = idx.weights[2];

    // How many results the panel shows before it stops. Value: 8,
    // enough to cover every heading of a typical query while keeping
    // the panel to about a screenful on a phone.
    var MAX_RESULTS = 8;

    // Score needed to keep a section at all: the same floor the home
    // page search uses, so both towers drop noise the same way.
    var CUTOFF_FLOOR = 0.08;
    var CUTOFF_RATIO = 0.35;

    // Step 2: lookup tables built once from the shipped index.
    var stop = {};
    idx.stopwords.forEach(function (w) { stop[w] = true; });
    var concepts = Object.keys(idx.concepts).map(function (name) {
        var set = {};
        idx.concepts[name].forEach(function (w) { set[w] = true; });
        return { name: name, set: set };
    });

    /* Lower-case and reduce text to a-z and 0-9 words (mirrors Python;
       "wi-fi" is folded into "wifi", other hyphens become gaps). */
    function normalise(text) {
        return text.toLowerCase().replace(/wi-fi/g, 'wifi')
            .replace(/[^a-z0-9]+/g, ' ').trim();
    }

    /* Strip plural "s", and "ing"/"ed" on long words (mirrors Python). */
    function stem(w) {
        if (w.length >= 6 && /ing$/.test(w)) { return w.slice(0, -3); }
        if (w.length >= 6 && /ed$/.test(w)) { return w.slice(0, -2); }
        if (w.length > 3 && /s$/.test(w) && !/ss$/.test(w)) {
            return w.slice(0, -1);
        }
        return w;
    }

    /* Stemmed, stop-word-free tokens. */
    function tokenise(text) {
        return normalise(text).split(' ').filter(function (w) {
            return w && !stop[w];
        }).map(stem);
    }

    /* 32-bit Fowler-Noll-Vo (FNV-1a) hash of an ASCII string; the
       Python tower uses the same constant and the same arithmetic. */
    function fnv1a(s) {
        var h = 2166136261;
        for (var i = 0; i < s.length; i++) {
            h ^= s.charCodeAt(i);
            h = Math.imul(h, 16777619) >>> 0;
        }
        return h >>> 0;
    }

    /* Query tower: text -> L2-normalised sparse vector {bucket: w}. */
    function encode(text) {
        var tokens = tokenise(text);
        var seen = {};
        var raw = {};
        function add(name, weight) {
            var b = fnv1a(name) % DIM;
            raw[b] = (raw[b] || 0) + weight;
        }
        tokens.forEach(function (tok) {
            seen[tok] = true;
            add('w:' + tok, W_WORD);
            var padded = '^' + tok + '$';
            for (var i = 0; i < padded.length - 2; i++) {
                add('g:' + padded.substr(i, 3), W_TRIGRAM);
            }
        });
        concepts.forEach(function (c) {
            for (var tok in seen) {
                if (c.set[tok]) {
                    add('c:' + c.name, W_CONCEPT);
                    break;
                }
            }
        });
        var vec = {};
        var norm = 0;
        for (var b in raw) {
            var v = (1 + Math.log(raw[b])) * idx.idf[b];
            vec[b] = v;
            norm += v * v;
        }
        norm = Math.sqrt(norm) || 1;
        for (var k in vec) { vec[k] /= norm; }
        return vec;
    }

    /* Cosine similarity of the query vector with one stored section,
       plus small bonuses when the literal phrase appears in the
       section text or in its heading. */
    function score(qvec, doc, qnorm) {
        var s = 0;
        for (var i = 0; i < doc.v.length; i++) {
            var q = qvec[doc.v[i][0]];
            if (q) { s += q * doc.v[i][1]; }
        }
        if (qnorm.length > 2 && doc.x.indexOf(qnorm) !== -1) { s += 0.15; }
        if (qnorm.length > 2 && doc.t.indexOf(qnorm) !== -1) { s += 0.1; }
        return s;
    }

    /* Empty the panel and clear the status line. */
    function clearPanel() {
        while (results.firstChild) { results.removeChild(results.firstChild); }
        results.hidden = true;
        status.textContent = '';
    }

    /*
     * Render the ranked list.
     *
     * Arguments:
     *   ranked: array of {doc, s} in best-first order.
     *   qnorm: the normalised query, used for the empty-state message.
     * Returns: undefined.
     * Side effects: rebuilds #doc-search-results, unhides it, and
     *   writes the count into #doc-search-status.
     *
     * Every text node is set with textContent, never innerHTML, so a
     * query can never inject markup into the panel.
     */
    function render(ranked, qnorm) {
        while (results.firstChild) { results.removeChild(results.firstChild); }

        if (!ranked.length) {
            results.hidden = true;
            status.textContent = 'No close match for "' + qnorm + '".';
            return;
        }

        ranked.forEach(function (entry) {
            var doc = entry.doc;
            var item = document.createElement('li');
            var link = document.createElement('a');
            link.href = doc.h;

            var title = document.createElement('span');
            title.className = 'doc-search-result-title';
            // "n" is the display title shipped by the index; "t" is
            // its normalised twin, used only as a fallback so a title
            // can never render blank.
            title.textContent = doc.n || doc.t || '';

            var page = document.createElement('span');
            page.className = 'doc-search-result-doc';
            page.textContent = doc.p || '';

            var snippet = document.createElement('span');
            snippet.className = 'doc-search-result-snippet';
            snippet.textContent = doc.s || '';

            link.appendChild(title);
            link.appendChild(page);
            link.appendChild(snippet);
            item.appendChild(link);
            results.appendChild(item);
        });

        results.hidden = false;
        status.textContent = ranked.length === 1
            ? '1 match, best first.'
            : ranked.length + ' matches, best first.';
    }

    /* Rank every section for the current query and show the best. */
    function run() {
        var qnorm = normalise(input.value);
        if (!qnorm) {
            clearPanel();
            return;
        }
        var qvec = encode(input.value);
        var ranked = [];
        var top = 0;
        idx.docs.forEach(function (doc) {
            var s = score(qvec, doc, qnorm);
            if (s > 0) { ranked.push({ doc: doc, s: s }); }
            if (s > top) { top = s; }
        });
        var cutoff = Math.max(CUTOFF_FLOOR, top * CUTOFF_RATIO);
        ranked = ranked.filter(function (r) { return r.s >= cutoff; });
        ranked.sort(function (a, b) { return b.s - a.s; });
        render(ranked.slice(0, MAX_RESULTS), qnorm);
    }

    // Step 3: typing updates the panel immediately. The corpus is 52
    // short sections, so scoring them on every keystroke costs less
    // than a debounce timer would.
    input.addEventListener('input', run);

    // Step 4: Enter in the box follows the best match, which is what a
    // reader who presses Enter obviously wants.
    input.addEventListener('keydown', function (event) {
        if (event.key === 'Enter') {
            var first = results.querySelector('a');
            if (first) {
                event.preventDefault();
                window.location.href = first.href;
            }
            return;
        }
        if (event.key === 'ArrowDown') {
            var firstDown = results.querySelector('a');
            if (firstDown) {
                event.preventDefault();
                firstDown.focus();
            }
            return;
        }
        if (event.key === 'Escape') {
            input.value = '';
            clearPanel();
        }
    });

    // Step 5: ArrowDown from a result moves on through the list, and
    // Escape from a result returns to the box, so the whole panel is
    // usable without a mouse.
    results.addEventListener('keydown', function (event) {
        var links = Array.prototype.slice.call(
            results.querySelectorAll('a'));
        var at = links.indexOf(document.activeElement);
        if (event.key === 'ArrowDown' && at < links.length - 1) {
            event.preventDefault();
            links[at + 1].focus();
        } else if (event.key === 'ArrowUp') {
            event.preventDefault();
            if (at > 0) { links[at - 1].focus(); } else { input.focus(); }
        } else if (event.key === 'Escape') {
            clearPanel();
            input.focus();
        }
    });

    // Step 6: a click or tap anywhere outside the form closes the
    // panel, so results never linger over the document underneath.
    document.addEventListener('pointerdown', function (event) {
        if (results.hidden) { return; }
        if (input.closest('.doc-search').contains(event.target)) {
            return;
        }
        clearPanel();
    });

    // Step 7: honour ?q=... so a link such as admin.html?q=refund
    // opens with the search already run, mirroring the home page.
    var initial = new URLSearchParams(window.location.search).get('q');
    if (initial) {
        input.value = initial;
        run();
    }
})();
